#!/usr/bin/env bash
# ============================================================================
# Migration Runner Script for PostgreSQL
# Applies all versioned migrations in order and records execution in schema_version.
# ============================================================================
set -euo pipefail

readonly DEFAULT_PGHOST="localhost"
readonly DEFAULT_PGPORT="5432"
readonly DEFAULT_PGUSER="postgres"
readonly DEFAULT_PGPASSWORD="postgres"
readonly DEFAULT_PGDATABASE="CRMDatabase"
readonly MS_PER_SECOND=1000

PGHOST="${PGHOST:-${DEFAULT_PGHOST}}"
PGPORT="${PGPORT:-${DEFAULT_PGPORT}}"
PGUSER="${PGUSER:-${DEFAULT_PGUSER}}"
PGPASSWORD="${PGPASSWORD:-${DEFAULT_PGPASSWORD}}"
PGDATABASE="${PGDATABASE:-${DEFAULT_PGDATABASE}}"

export PGPASSWORD

run_psql_query() {
    local target_db="$1"
    shift
    psql -h "${PGHOST}" -p "${PGPORT}" -U "${PGUSER}" -d "${target_db}" -v ON_ERROR_STOP=1 "$@"
}

# psql only interpolates :'variables' in scripts read from stdin or -f (never in -c),
# so parameterized statements are streamed through stdin.
run_psql_parameterized() {
    local target_db="$1"
    local sql="$2"
    shift 2
    run_psql_query "${target_db}" "$@" <<< "${sql}"
}

echo "==> Connecting to PostgreSQL at ${PGHOST}:${PGPORT}/${PGDATABASE} as user '${PGUSER}'..."

echo "==> Waiting for PostgreSQL to be ready at ${PGHOST}:${PGPORT}..."
MAX_RETRIES=30
RETRY_COUNT=0
until pg_isready -h "${PGHOST}" -p "${PGPORT}" -U "${PGUSER}" >/dev/null 2>&1 || [ "${RETRY_COUNT}" -eq "${MAX_RETRIES}" ]; do
    RETRY_COUNT=$((RETRY_COUNT + 1))
    echo "  PostgreSQL not ready yet, retrying in 2s (${RETRY_COUNT}/${MAX_RETRIES})..."
    sleep 2
done

if [ "${RETRY_COUNT}" -eq "${MAX_RETRIES}" ]; then
    echo "Error: PostgreSQL is not reachable at ${PGHOST}:${PGPORT} after ${MAX_RETRIES} attempts." >&2
    exit 1
fi

# Ensure target database exists using parameterized psql variables
run_psql_parameterized postgres "SELECT 1 FROM pg_database WHERE datname = :'target_db';" -v target_db="${PGDATABASE}" -tA | grep -q 1 \
    || run_psql_query postgres -c "CREATE DATABASE \"${PGDATABASE}\";"


SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
MIGRATIONS_DIR="${SCRIPT_DIR}/migrations"

echo "==> Scanning migrations directory: ${MIGRATIONS_DIR}"

readonly SCHEMA_VERSION_SQL="
CREATE TABLE IF NOT EXISTS public.schema_version (
    installed_rank INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version VARCHAR(50) NOT NULL UNIQUE,
    description VARCHAR(200) NOT NULL,
    type VARCHAR(20) NOT NULL DEFAULT 'SQL',
    script VARCHAR(1000) NOT NULL,
    checksum VARCHAR(64) NULL,
    installed_by VARCHAR(100) NOT NULL DEFAULT CURRENT_USER,
    installed_on TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    execution_time_ms INTEGER NOT NULL DEFAULT 0,
    success BOOLEAN NOT NULL DEFAULT TRUE
);"

sql_literal() {
    local value="${1//"'"/"''"}"
    printf "'%s'" "${value}"
}

build_migration_step() {
    local migration_file="$1"
    local filename
    local version
    local description
    local version_literal
    local description_literal
    local script_literal
    local file_literal

    filename="$(basename "${migration_file}")"
    version="$(echo "${filename}" | sed -E 's/^V([0-9]+)__.*$/\1/')"
    description="$(echo "${filename}" | sed -E 's/^V[0-9]+__(.*)\.sql$/\1/' | tr '_' ' ')"
    version_literal="$(sql_literal "${version}")"
    description_literal="$(sql_literal "${description}")"
    script_literal="$(sql_literal "${filename}")"
    file_literal="$(sql_literal "${migration_file}")"

    cat <<EOF
SELECT EXISTS (SELECT 1 FROM public.schema_version WHERE version = ${version_literal} AND success = TRUE) AS applied \gset
\if :applied
\echo   [SKIP] Migration V${version} (${filename}) already applied.
\else
\echo   [APPLYING] Migration V${version}: ${filename}...
SELECT clock_timestamp() AS mig_start \gset
BEGIN;
\i ${file_literal}
INSERT INTO public.schema_version (version, description, script, execution_time_ms, success)
VALUES (
    ${version_literal},
    ${description_literal},
    ${script_literal},
    CAST(EXTRACT(EPOCH FROM (clock_timestamp() - :'mig_start'::timestamptz)) * ${MS_PER_SECOND} AS INTEGER),
    TRUE
);
COMMIT;
\echo   [SUCCESS] Migration V${version} applied.
\endif
EOF
}

build_migration_session() {
    printf '%s\n' "SELECT pg_advisory_lock(hashtext('crm_migration_lock'));"
    printf '%s\n' "${SCHEMA_VERSION_SQL}"
    while IFS= read -r migration_file; do
        build_migration_step "${migration_file}"
    done < <(find "${MIGRATIONS_DIR}" -maxdepth 1 -name 'V*.sql' | sort -V)
    printf '%s\n' "SELECT pg_advisory_unlock(hashtext('crm_migration_lock'));"
}

echo "==> Applying migrations in one session holding the advisory lock..."
build_migration_session | run_psql_query "${PGDATABASE}"

echo "==> All migrations are up to date!"
