#!/usr/bin/env python3
"""
Migration Runner for PostgreSQL CRM Database.
Provides a database-agnostic CLI runner compatible with Flyway naming conventions.
"""
from __future__ import annotations

from dataclasses import dataclass
import glob
import os
import re
import subprocess
import sys

DEFAULT_PGHOST: str = "localhost"
DEFAULT_PGPORT: str = "5432"
DEFAULT_PGUSER: str = "postgres"
DEFAULT_PGPASSWORD: str = "postgres"
DEFAULT_PGDATABASE: str = "CRMDatabase"
MS_PER_SECOND: int = 1000

INIT_SCHEMA_VERSION_SQL: str = """
CREATE TABLE IF NOT EXISTS public.schema_version (
    installed_rank INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version VARCHAR(50) NOT NULL UNIQUE,
    description VARCHAR(200) NOT NULL,
    type VARCHAR(20) NOT NULL DEFAULT 'SQL',
    script VARCHAR(1000) NOT NULL,
    checksum VARCHAR(64) NULL,
    installed_by VARCHAR(100) NOT NULL DEFAULT CURRENT_USER,
    installed_on TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    execution_time_ms INTEGER NOT NULL DEFAULT 0,
    success BOOLEAN NOT NULL DEFAULT TRUE
);
"""


@dataclass(frozen=True)
class PostgresMigrationConfig:
    """Immutable connection configuration for PostgreSQL migration execution."""
    host: str
    port: str
    user: str
    password: str
    database: str


@dataclass(frozen=True)
class MigrationDescriptor:
    """Immutable descriptor representing a single versioned Flyway SQL migration file."""
    filepath: str
    filename: str
    version: str
    description: str


def resolve_config() -> PostgresMigrationConfig:
    """Pure query reading PostgreSQL connection parameters from environment variables."""
    return PostgresMigrationConfig(
        host=os.environ.get("PGHOST", DEFAULT_PGHOST),
        port=os.environ.get("PGPORT", DEFAULT_PGPORT),
        user=os.environ.get("PGUSER", DEFAULT_PGUSER),
        password=os.environ.get("PGPASSWORD", DEFAULT_PGPASSWORD),
        database=os.environ.get("PGDATABASE", DEFAULT_PGDATABASE),
    )


def natural_sort_key(filepath: str) -> tuple[int | str, ...]:
    """Pure key function sorting versioned migration filenames naturally."""
    return tuple(
        int(token) if token.isdigit() else token
        for token in re.split(r"(\d+)", os.path.basename(filepath))
    )


def parse_migration_descriptor(filepath: str) -> MigrationDescriptor:
    """Pure transformation parsing a migration filepath into an immutable descriptor."""
    filename = os.path.basename(filepath)
    parts = filename.split("__", 1)
    version = parts[0].removeprefix("V")
    description = parts[1].removesuffix(".sql").replace("_", " ") if len(parts) > 1 else ""
    return MigrationDescriptor(
        filepath=filepath,
        filename=filename,
        version=version,
        description=description,
    )


def run_psql(
    config: PostgresMigrationConfig,
    sql: str | None = None,
    filepath: str | None = None,
    variables: dict[str, str] | None = None,
    check: bool = True,
) -> subprocess.CompletedProcess[str]:
    """Explicit side-effecting helper executing a parameterized psql command."""
    env = {**os.environ, "PGPASSWORD": config.password}
    var_flags = [
        flag
        for key, val in (variables or {}).items()
        for flag in ("-v", f"{key}={val}")
    ]
    action_flags = (
        ["--single-transaction", "-f", filepath]
        if filepath
        else []
    )
    cmd = [
        "psql",
        "-h", config.host,
        "-p", config.port,
        "-U", config.user,
        "-d", config.database,
        "-v", "ON_ERROR_STOP=1",
        *var_flags,
        *action_flags,
    ]
    res = subprocess.run(
        cmd,
        input=sql if sql is not None else None,
        env=env,
        capture_output=True,
        text=True,
        check=False,
    )
    if check and res.returncode != 0:
        print(f"Error executing SQL:\n{res.stderr}", file=sys.stderr)
        sys.exit(res.returncode)
    return res


ACQUIRE_LOCK_SQL: str = "SELECT pg_advisory_lock(hashtext('crm_migration_lock'));"
RELEASE_LOCK_SQL: str = "SELECT pg_advisory_unlock(hashtext('crm_migration_lock'));"


def quote_sql_literal(value: str) -> str:
    """Pure transformation escaping a value as a single-quoted SQL string literal."""
    return "'" + value.replace("'", "''") + "'"


def build_migration_step(descriptor: MigrationDescriptor) -> str:
    """Pure transformation rendering the psql script fragment that applies one migration if pending and records it."""
    version = quote_sql_literal(descriptor.version)
    description = quote_sql_literal(descriptor.description)
    script = quote_sql_literal(descriptor.filename)
    return f"""
SELECT EXISTS (SELECT 1 FROM public.schema_version WHERE version = {version} AND success = TRUE) AS applied \\gset
\\if :applied
\\echo   [SKIP] Migration V{descriptor.version} ({descriptor.filename}) already applied.
\\else
\\echo   [APPLYING] Migration V{descriptor.version}: {descriptor.filename}...
SELECT clock_timestamp() AS mig_start \\gset
BEGIN;
\\i {quote_sql_literal(descriptor.filepath)}
INSERT INTO public.schema_version (version, description, script, execution_time_ms, success)
VALUES (
    {version},
    {description},
    {script},
    CAST(EXTRACT(EPOCH FROM (clock_timestamp() - :'mig_start'::timestamptz)) * {MS_PER_SECOND} AS INTEGER),
    TRUE
);
COMMIT;
\\echo   [SUCCESS] Migration V{descriptor.version} applied.
\\endif
"""


def build_migration_script(descriptors: tuple[MigrationDescriptor, ...]) -> str:
    """Pure transformation composing one psql session script: lock, schema table, migrations, unlock."""
    return "\n".join((ACQUIRE_LOCK_SQL, INIT_SCHEMA_VERSION_SQL, *map(build_migration_step, descriptors), RELEASE_LOCK_SQL))


def main() -> None:
    config = resolve_config()
    print(f"==> Connecting to PostgreSQL at {config.host}:{config.port}/{config.database}...")

    base_dir = os.path.dirname(os.path.abspath(__file__))
    migrations_dir = os.path.join(base_dir, "migrations")
    sorted_files = sorted(glob.glob(os.path.join(migrations_dir, "V*.sql")), key=natural_sort_key)
    descriptors = tuple(map(parse_migration_descriptor, sorted_files))

    print(f"==> Found {len(descriptors)} migration files in {migrations_dir}")
    print("==> Applying migrations in one session holding the advisory lock...")
    res = run_psql(config, sql=build_migration_script(descriptors))
    print(res.stdout, end="")
    print("==> All migrations applied successfully!")


if __name__ == "__main__":
    main()
